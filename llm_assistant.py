class LocalLLMAssistant:
    """Local LLM Assistant using transformers"""

    def __init__(self):
        self.model = None
        self.tokenizer = None
        self.model_loaded = False
        self.load_model()

    def load_model(self):
        """Load a local model"""
        try:
            model_name = "microsoft/DialoGPT-medium"
            print("⏳ Loading local AI model...")

            from transformers import AutoTokenizer, AutoModelForCausalLM
            self.tokenizer = AutoTokenizer.from_pretrained(model_name)
            self.model = AutoModelForCausalLM.from_pretrained(model_name)

            if self.tokenizer.pad_token is None:
                self.tokenizer.pad_token = self.tokenizer.eos_token

            self.model_loaded = True
            print("✅ Local AI model loaded:", model_name)

        except Exception as e:
            print(f"❌ Failed to load local model: {e}")
            self.model_loaded = False

    def generate_response(self, user_query: str, budget_context: str = "") -> Optional[str]:
        """Generate response using local model"""
        if not self.model_loaded:
            print("⚠️ Local model not loaded, skipping")
            return None

        try:
            import torch
            prompt = f"Financial Advisor: {user_query}\n\nBudget Info: {budget_context}\n\nResponse:"

            inputs = self.tokenizer.encode(prompt, return_tensors="pt", max_length=200, truncation=True)

            with torch.no_grad():
                outputs = self.model.generate(
                    inputs,
                    max_length=inputs.shape[1] + 150,
                    temperature=0.8,
                    do_sample=True,
                    top_p=0.9,
                    top_k=50,
                    repetition_penalty=1.2,
                    pad_token_id=self.tokenizer.eos_token_id,
                    eos_token_id=self.tokenizer.eos_token_id,
                    no_repeat_ngram_size=2
                )

            full_response = self.tokenizer.decode(outputs[0], skip_special_tokens=True)
            if "Response:" in full_response:
                response = full_response.split("Response:")[-1].strip()
            else:
                response = full_response.replace(prompt, "").strip()

            print("✅ Response generated by Local model")
            return response if len(response) > 20 else None

        except Exception as e:
            print(f"❌ Local model error: {e}")
            return None


    
    def _validate_response(self, response: str) -> bool:
        """Validate response quality"""
        if not response or len(response.strip()) < 20:
            return False
        
        # Check for financial relevance
        financial_keywords = [
            "money", "budget", "save", "invest", "debt", "income", "expense",
            "financial", "finance", "dollar", "cost", "price", "pay", "earn",
            "spend", "wealth", "retirement", "insurance", "credit", "loan"
        ]
        
        response_lower = response.lower()
        has_financial_content = any(keyword in response_lower for keyword in financial_keywords)
        
        # Check for inappropriate content
        bad_patterns = [
            "hack", "brain", "mind powers", "drunk", "games", "targets",
            "ai but then", "data there was", "move on", "pain in the ass"
        ]
        
        has_bad_content = any(pattern in response_lower for pattern in bad_patterns)
        
        return has_financial_content and not has_bad_content

