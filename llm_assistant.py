class AdvancedFinanceLLMAssistant:
    """Advanced LLM Assistant using Hugging Face Inference API"""

    def __init__(self, hf_token: str):
        self.api_available = False
        self.fallback_mode = False
        self.hf_token = 'hf_token'
        self.setup_api()

    def setup_api(self):
        """Setup API connection and test availability"""
        if not self.hf_token or not self.hf_token.startswith("hf_"):
            print("⚠️ No valid Hugging Face token provided → using fallback mode")
            self.fallback_mode = True
            return

        self.api_available = True
        print("✅ Hugging Face API mode enabled")

    def _make_api_request(self, query: str, model: str) -> Optional[str]:
        """Make a request to Hugging Face Inference API"""
        try:
            url = f"https://api-inference.huggingface.co/models/{model}"
            headers = {
                "Authorization": f"Bearer {self.hf_token}",
                "Content-Type": "application/json"
            }
            payload = {
                "inputs": query,
                "parameters": {
                    "max_length": 200,
                    "temperature": 0.7,
                    "do_sample": True,
                    "top_p": 0.9,
                    "return_full_text": False
                }
            }

            response = requests.post(url, headers=headers, json=payload, timeout=15)
            if response.status_code == 200:
                print(f"✅ Response generated by API model: {model}")
                return response.json()[0].get('generated_text', '').strip()
            else:
                print(f"⚠️ API call failed for {model} (status {response.status_code})")
                return None

        except Exception as e:
            print(f"❌ API request error for {model}: {e}")
            return None

    def generate_response(self, user_query: str, budget_context: str = "") -> Optional[str]:
        """Generate a response using advanced LLM models"""
        if not self.api_available or self.fallback_mode:
            print("⚠️ API not available, skipping to fallback")
            return None

        try:
            prompt = self._create_financial_prompt(user_query, budget_context)
            models = [
                "meta-llama/Llama-2-7b-chat-hf",  # Strongest
                "microsoft/DialoGPT-medium",      # Medium
                "gpt2"                            # Weak fallback
            ]

            for model in models:
                response = self._make_api_request(prompt, model)
                if response and self._validate_response(response):
                    return self._clean_response(response)

            print("⚠️ All API models failed, using fallback")
            return None

        except Exception as e:
            print(f"❌ Error generating LLM response: {e}")
            return None

    def _create_financial_prompt(self, user_query: str, budget_context: str) -> str:
        return f"""You are a helpful and knowledgeable personal finance assistant.

Budget Context:
{budget_context}

User Question: {user_query}

Please provide a helpful, friendly, and accurate response about personal finance.
Keep it concise but informative.

Response:"""

    def _validate_response(self, response: str) -> bool:
        if not response or len(response.strip()) < 20:
            return False

        financial_keywords = [
            "money", "budget", "save", "invest", "debt", "income", "expense",
            "financial", "finance", "dollar", "cost", "price", "pay", "earn",
            "spend", "wealth", "retirement", "insurance", "credit", "loan"
        ]
        response_lower = response.lower()
        has_financial_content = any(k in response_lower for k in financial_keywords)

        bad_patterns = ["hack", "drunk", "pain in the ass", "ai but then"]
        has_bad_content = any(b in response_lower for b in bad_patterns)

        return has_financial_content and not has_bad_content

    def _clean_response(self, response: str) -> str:
        if "Response:" in response:
            response = response.split("Response:")[-1].strip()
        if "User Question:" in response:
            response = response.split("User Question:")[0].strip()
        if len(response) > 500:
            response = response[:500] + "..."
        return response.strip()


